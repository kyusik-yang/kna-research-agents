def _claim_properties() -> dict:
    num_or_range = {"oneOf": [
        {"type": "number"},
        {"type": "array", "items": {"type": "number"}, "minItems": 2, "maxItems": 2},
    ]}
    return {
        "claim_id": {"type": "string", "description": "Stable id of the claim within the arc."},
        "quantity_id": {"type": "string", "description": "Id of the measured quantity in knowledge/quantities.jsonl."},
        "quantity": {"type": "string", "description": "The measurable KNA quantity in words."},
        "population": {"type": "string"},
        "period": {"type": "string"},
        "comparison": {"type": "string"},
        "direction": {"type": "string", "enum": list(DIRECTIONS)},
        "supporting_result": {"type": "string"},
        "decisive_metric": {"type": "string"},
        "falsifying_result": {"type": "string"},
        "threshold": {**num_or_range, "description": "Number, or [low, high], in the stated units."},
        "units": {"type": "string"},
        "decision_rule_quoted": {"type": "string", "description": "Verbatim copy of the gate's decision_rule."},
        "equivalence_bound": {"type": ["number", "null"], "description": "Bound for any null this claim could report, in the stated units. Defaults to the gate's sesoi."},
        "claim_scope": {"type": "string"},
        "supersedes": {"type": ["string", "null"], "description": "claim_id whose threshold this claim replaces."},
    }


def _quote_side() -> dict:
    return {
        "type": "object",
        "properties": {
            "doi": {"type": "string"},
            "quoted_prediction": {"type": ["string", "null"], "description": "A verbatim sentence from the source."},
            "location": {"type": ["string", "null"], "description": "abstract, page N or section N."},
            "quantity_match": {"type": "string", "enum": list(QUANTITY_MATCH)},
        },
        "required": ["doi", "quoted_prediction", "location", "quantity_match"],
    }


def build_card_schema() -> dict:
    spec = {
        "type": "object",
        "properties": {
            "spec_id": {"type": "string", "description": "Identifier. x_ ids are reserved for exploratory results."},
            "role": {"type": "string", "enum": list(ROLES)},
            "claim_id": {"type": "string", "description": "Claim the spec tests. Defaults to the card's claim_id."},
            "outcome_def": {"type": "string"},
            "sample_def": {"type": "string"},
            "model": {"type": "string"},
            "expected_n": {"type": ["integer", "null"]},
            "what_result_would_mean": {"type": "string", "description": "The alternative explanation this spec rules out. Required for every role."},
            "sanity_kind": {"type": "string", "enum": list(SANITY_KINDS)},
            "draws": {"type": "integer"},
            "source": {"type": "object", "description": "Calibration specs only: the cited DOI and table or page."},
        },
        "required": list(SPEC_KEYS),
    }
    claim_props = _claim_properties()
    gap = {
        "type": "object",
        "properties": {
            "gap_type": {"type": "string", "enum": list(GAP_TYPES)},
            "evidence": {"type": "object", "properties": {
                "lit_a": _quote_side(), "lit_b": _quote_side(),
                "own_derivation": {"type": "boolean"},
                "theory_source": {"type": "string"}, "quoted_prediction": {"type": ["string", "null"]},
                "location": {"type": ["string", "null"]}, "magnitude": {"type": "string"},
                "measure": {"type": "string"}, "why_unavailable": {"type": "string"},
                "available_since": {"type": "string"},
            }},
        },
        "required": ["gap_type", "evidence"],
    }
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "card.v1",
        "title": "Prediction card",
        "description": ("Committed before the Analyst runs. The validator in prediction_card.py "
                        "adds the conditional rules (one primary spec, at most six specs, sanity "
                        "specs for effect claims, gap evidence, threshold supersession)."),
        "type": "object",
        "properties": {
            "kind": {"type": "string", "enum": list(KINDS)},
            **claim_props,
            "gap": gap,
            "claims": {"type": "array", "items": {"type": "object", "properties": claim_props,
                                                  "required": list(CLAIM_KEYS)}},
            "spec_plan": {"type": "array", "items": spec, "minItems": 1, "maxItems": MAX_SPECS},
        },
        "required": ["claim_id", "kind", "spec_plan"],
    }


def load_card_schema() -> dict:
    return json.loads(CARD_SCHEMA_FILE.read_text(encoding="utf-8"))


def write_card_schema() -> Path:
    path = CARD_SCHEMA_FILE
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(build_card_schema(), ensure_ascii=False, indent=2) + "\n",
                    encoding="utf-8")
    return path


def schema_errors(obj, schema: dict, path: str = "$") -> list[str]:
    """Small JSON-schema subset validator (type, enum, required, properties,
    items, min/max, minItems/maxItems, maxLength, oneOf, additionalProperties).
    Kept here so the evidence modules need no third-party validator."""
    errs: list[str] = []
    if "oneOf" in schema:
        if not any(not schema_errors(obj, s, path) for s in schema["oneOf"]):
            errs.append(f"{path}: does not match any allowed form")
        return errs
    t = schema.get("type")
    if t is not None:
        types = t if isinstance(t, list) else [t]
        if not any(_type_ok(obj, x) for x in types):
            return [f"{path}: expected {'/'.join(types)}, got {type(obj).__name__}"]
    if "enum" in schema and obj not in schema["enum"]:
        errs.append(f"{path}: {obj!r} not in {schema['enum']}")
    if isinstance(obj, (int, float)) and not isinstance(obj, bool):
        if "minimum" in schema and obj < schema["minimum"]:
            errs.append(f"{path}: {obj} < {schema['minimum']}")
        if "maximum" in schema and obj > schema["maximum"]:
            errs.append(f"{path}: {obj} > {schema['maximum']}")
    if isinstance(obj, str) and "maxLength" in schema and len(obj) > schema["maxLength"]:
        errs.append(f"{path}: longer than {schema['maxLength']} characters")
    if isinstance(obj, list):
        if "minItems" in schema and len(obj) < schema["minItems"]:
            errs.append(f"{path}: fewer than {schema['minItems']} items")
        if "maxItems" in schema and len(obj) > schema["maxItems"]:
            errs.append(f"{path}: more than {schema['maxItems']} items")
        if "items" in schema:
            for i, x in enumerate(obj):
                errs += schema_errors(x, schema["items"], f"{path}[{i}]")
    if isinstance(obj, dict):
        props = schema.get("properties", {})
        for k in schema.get("required", []):
            if k not in obj:
                errs.append(f"{path}: missing required field '{k}'")
        for k, v in obj.items():
            if k in props:
                errs += schema_errors(v, props[k], f"{path}.{k}")
            elif schema.get("additionalProperties") is False:
                errs.append(f"{path}: unexpected field '{k}'")
    return errs


def _type_ok(obj, t: str) -> bool:
    if t == "object":
        return isinstance(obj, dict)
    if t == "array":
        return isinstance(obj, list)
    if t == "string":
        return isinstance(obj, str)
    if t == "integer":
        return isinstance(obj, int) and not isinstance(obj, bool)
    if t == "number":
        return isinstance(obj, (int, float)) and not isinstance(obj, bool)
    if t == "boolean":
        return isinstance(obj, bool)
    if t == "null":
        return obj is None
    return True


