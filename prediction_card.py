def signature(spec: dict) -> tuple:
    """Normalized (outcome_def, sample_def, model) used to decide whether a
    spec is new for its claim (M10b kill specs)."""
    def n(s):
        return re.sub(r"[^a-z0-9]+", " ", str(s or "").lower()).strip()
    return (n(spec.get("outcome_def")), n(spec.get("sample_def")), n(spec.get("model")))


def canonical_json(card: dict) -> str:
    return json.dumps(card, ensure_ascii=False, indent=2, sort_keys=True) + "\n"


def card_sha(card: dict) -> str:
    return hashlib.sha256(canonical_json(card).encode("utf-8")).hexdigest()


def card_path(round_num: int, cards_dir: Path | None = None) -> Path:
    return (cards_dir or CARDS_DIR) / f"R{int(round_num):02d}.json"


def _now_iso() -> str:
    return datetime.now(timezone.utc).astimezone().isoformat(timespec="seconds")


def _rel(p: Path | str | None) -> str | None:
    if p is None:
        return None
    p = Path(p)
    try:
        return str(p.resolve().relative_to(BASE_DIR))
    except ValueError:
        return p.name


def _git(args: list[str], repo: Path) -> subprocess.CompletedProcess:
    return subprocess.run(["git", *args], cwd=str(repo), capture_output=True, text=True)


def data_exposed_from_trace(events: list[dict]) -> bool:
    """True when the Scout's trace shows reads of KNA or kr-hearings data
    files before the card was written (recorded, not blocked)."""
    for call in _tool_calls(events):
        blob = json.dumps(call.get("input") or {}, ensure_ascii=False)
        if DATA_TOUCH_RE.search(blob):
            return True
    return False


def _tool_calls(events: list[dict]) -> list[dict]:
    out = []
    for e in events or []:
        msg = e.get("message") if isinstance(e.get("message"), dict) else None
        for item in (msg or {}).get("content") or []:
            if isinstance(item, dict) and item.get("type") == "tool_use":
                out.append({"name": item.get("name"), "input": item.get("input") or {}})
    return out


def commit_card(round_num: int, card: dict, source_post, *, gate: dict | None = None,
                data_exposed: bool | None = None, committed_at: str | None = None,
                git_commit: bool = False, check: bool = True,
                cards_dir: Path | None = None) -> Path:
    """Write knowledge/prediction_cards/R<NN>.json and append its index row.

    Refuses an invalid card (ValueError with the errors) unless check=False,
    and never overwrites a committed card with different content
    (FileExistsError). With git_commit=True it also commits the card and index
    paths only (git commit -- <paths>), which timestamps the pre-commitment in
    history. The index row records the HEAD at commit time as git_head."""
    cards_dir = cards_dir or CARDS_DIR
    index_path = cards_dir / "index.jsonl"
    card = json.loads(json.dumps(card))   # detach from the caller's object
    if check:
        errs = validate(card, gate, load_cards(cards_dir))
        if errs:
            raise ValueError("invalid card: " + "; ".join(errs))
    sesoi = (gate or {}).get("sesoi")
    if card.get("kind", "prediction") == "prediction" and card.get("equivalence_bound") is None \
            and _is_num(_first_number(sesoi)):
        card["equivalence_bound"] = _first_number(sesoi)
    out = card_path(round_num, cards_dir)
    text = canonical_json(card)
    sha = hashlib.sha256(text.encode("utf-8")).hexdigest()
    if out.exists():
        if out.read_text(encoding="utf-8") == text:
            return out
        raise FileExistsError(f"{out.name} is already committed with different content; "
                              "a changed prediction needs a new claim with 'supersedes'")
    cards_dir.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    repo = cards_dir
    head = None
    top = _git(["rev-parse", "--show-toplevel"], repo)
    if top.returncode == 0:
        repo = Path(top.stdout.strip())
        h = _git(["rev-parse", "HEAD"], repo)
        head = h.stdout.strip() if h.returncode == 0 else None
    row = {
        "round": int(round_num),
        "claim_ids": [c.get("claim_id") for c in all_claims(card)],
        "kind": card.get("kind", "prediction"),
        "sha256": sha,
        "committed_at": committed_at or _now_iso(),
        "git_head": head,
        "data_exposed": data_exposed,
        "source_post": _rel(source_post) if source_post else None,
        **gap_record(card),
    }
    with open(index_path, "a", encoding="utf-8") as f:
        f.write(json.dumps(row, ensure_ascii=False) + "\n")
    if git_commit and top.returncode == 0:
        paths = [str(out.resolve().relative_to(repo)), str(index_path.resolve().relative_to(repo))]
        _git(["add", "--", *paths], repo)
        msg = f"Card R{int(round_num):02d}: {', '.join(x for x in row['claim_ids'] if x)}"
        c = _git(["commit", "-m", msg, "--", *paths], repo)
        if c.returncode != 0:
            print(f"  [Card] git commit failed: {c.stderr.strip()[:200]}")
    print(f"  [Card] R{int(round_num):02d} committed ({sha[:12]}), claims {row['claim_ids']}")
    return out


def _first_number(x):
    if _is_num(x):
        return x
    m = re.search(r"[-+]?\d+(?:\.\d+)?", str(x or ""))
    return float(m.group(0)) if m else None


def load_index(cards_dir: Path | None = None) -> list[dict]:
    return _read_jsonl((cards_dir or CARDS_DIR) / "index.jsonl")


def card_meta(cards_dir: Path | None = None) -> dict:
    """{round: index row} (the first row per round)."""
    out = {}
    for r in load_index(cards_dir):
        out.setdefault(int(r["round"]), r)
    return out


def load_cards(cards_dir: Path | None = None) -> dict:
    """{round: card} for every committed card."""
    d = cards_dir or CARDS_DIR
    out = {}
    for p in sorted(d.glob("R*.json")) if d.exists() else []:
        m = re.match(r"^R(\d+)$", p.stem)
        if not m:
            continue
        try:
            out[int(m.group(1))] = json.loads(p.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            continue
    return out


def results_dir(round_num: int) -> Path:
    return WORKSPACE_DIR / f"r{int(round_num)}" / "results"


def load_results(round_num: int | None = None, rdir: Path | None = None) -> dict:
    """{spec_id: result dict} from workspace/rNN/results/*.json."""
    d = rdir or results_dir(round_num)
    out = {}
    for p in sorted(d.glob("*.json")) if d and d.exists() else []:
        try:
            res = json.loads(p.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            continue
        if isinstance(res, dict):
            res.setdefault("spec_id", p.stem)
            res.setdefault("_path", str(p))
            out[str(res["spec_id"])] = res
    return out


def _read_jsonl(path: Path) -> list[dict]:
    if not path or not Path(path).exists():
        return []
    rows = []
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            rows.append(json.loads(line))
        except json.JSONDecodeError:
            continue
    return rows


def _ts(s) -> datetime | None:
    if not s:
        return None
    try:
        dt = datetime.fromisoformat(str(s).replace("Z", "+00:00"))
    except ValueError:
        return None
    return dt if dt.tzinfo else dt.astimezone()


def _result_time(res: dict) -> datetime | None:
    t = _ts(res.get("created_at"))
    if t is None and res.get("_path") and Path(res["_path"]).exists():
        t = datetime.fromtimestamp(Path(res["_path"]).stat().st_mtime).astimezone()
    return t


def _thresholds_set(claim: dict | None) -> list:
    if not claim:
        return []
    return [v for v in (claim.get("threshold"), claim.get("equivalence_bound")) if v is not None]


def _margins(res: dict) -> list:
    """Thresholds or equivalence margins a results file applies (numbers or lists)."""
    return [res[k] for k in ("threshold", "equivalence_margin") if res.get(k) is not None]


def _abs_set(vals) -> set:
    out = set()
    for v in vals:
        if isinstance(v, list):
            out |= {abs(float(x)) for x in v if _is_num(x)}
        elif _is_num(v):
            out.add(abs(float(v)))
    return out


def ingest_results(round_num: int, card: dict | None = None, results: dict | None = None, *,
                   arc_start: int | None = None, cards: dict | None = None,
                   meta: dict | None = None, quantities_path: Path | None = None,
                   arc: str | int | None = None) -> list[dict]:
    """Append this round's results to knowledge/quantities.jsonl and return
    the new rows. Idempotent on (round, spec_id).

    status rules, in order:
      not_computable  the results file says NOT COMPUTABLE (kept, never a prior)
      post_hoc      a threshold or margin is set this round on a quantity that
                    already has an estimate from an earlier round
      exploratory   an x_ spec, a spec not on the committed card, or a quantity
                    that was exploratory earlier in the arc (sticky)
      confirmatory  the quantity's first estimate came from a card spec
                    committed before the estimate
    """
    qpath = quantities_path or QUANTITIES_FILE
    cards = cards if cards is not None else load_cards()
    meta = meta if meta is not None else card_meta()
    if card is None:
        card = cards.get(int(round_num))
    results = results if results is not None else load_results(round_num)
    existing = _read_jsonl(qpath)
    start = arc_start if arc_start is not None else min(cards) if cards else int(round_num)
    arc_rows = [r for r in existing if start <= int(r.get("round", 0)) < int(round_num)]
    done = {(int(r["round"]), r["spec_id"]) for r in existing if "spec_id" in r}
    specs = {s.get("spec_id"): s for s in (card or {}).get("spec_plan") or []}
    m = meta.get(int(round_num)) or {}
    committed = _ts(m.get("committed_at"))
    sha = m.get("sha256") or (card_sha(card) if card else None)
    # Thresholds already on earlier arc cards, by claim and by quantity
    earlier_claims, earlier_q_thr, claim_qid = set(), {}, {}
    for r in sorted(cards):
        if start <= r < int(round_num):
            for c in all_claims(cards[r]):
                earlier_claims.add(c.get("claim_id"))
                earlier_q_thr.setdefault(c.get("quantity_id"), set()).update(_abs_set(_thresholds_set(c)))
                if c.get("quantity_id"):
                    claim_qid.setdefault(c.get("claim_id"), c.get("quantity_id"))
    new_rows = []
    for spec_id in sorted(results):
        if (int(round_num), spec_id) in done:
            continue
        res = results[spec_id]
        spec = specs.get(spec_id)
        cid = res.get("claim_id") or (spec_claim_id(card, spec) if (card and spec) else None)
        claim = claim_by_id(card, cid) if card else None
        qid = res.get("quantity_id") or (claim or {}).get("quantity_id") or claim_qid.get(cid) or spec_id
        # Only estimates from earlier rounds count as prior (same-round specs are siblings).
        prior = [r for r in arc_rows if r.get("quantity_id") == qid and int(r.get("round", 0)) < int(round_num)
                 and r.get("status") != "not_computable"]
        new_thr = False
        if claim and cid not in earlier_claims and _thresholds_set(claim):
            new_thr = True
        known = earlier_q_thr.get(qid, set()) | _abs_set(_thresholds_set(claim))
        if _abs_set(_margins(res)) - known:
            new_thr = True
        reason = ""
        if str(res.get("status", "")).lower() == "not_computable":
            status, reason = "not_computable", str(res.get("missing_variable") or "")
        elif prior and new_thr:
            status, reason = "post_hoc", f"threshold set in R{round_num} after estimate in R{prior[0]['round']}"
        elif spec_id.startswith("x_") or spec is None:
            status, reason = "exploratory", "not a committed card spec"
        elif prior:
            status = prior[0].get("status", "exploratory")
            if status == "post_hoc":
                status = "exploratory"
            reason = f"sticky from R{prior[0]['round']}"
        else:
            t = _result_time(res)
            if committed and t and committed < t:
                status, reason = "confirmatory", "card committed before the first estimate"
            else:
                status, reason = "exploratory", "card not committed before the first estimate"
        ci = [res.get("ci_low"), res.get("ci_high")]
        row = {
            "ts": _now_iso(),
            "round": int(round_num),
            "arc": arc,
            "quantity_id": qid,
            "spec_id": spec_id,
            "claim_id": cid,
            "estimate": res.get("estimate"),
            "se": res.get("se"),
            "ci": ci if any(v is not None for v in ci) else None,
            "n": res.get("n"),
            "output_path": _rel(res["_path"]) if res.get("_path") else None,
            "script": res.get("script"),
            "card_sha": sha,
            "status": status,
            "reason": reason,
        }
        new_rows.append(row)
        arc_rows.append(row)
    if new_rows:
        qpath.parent.mkdir(parents=True, exist_ok=True)
        with open(qpath, "a", encoding="utf-8") as f:
            for row in new_rows:
                f.write(json.dumps(row, ensure_ascii=False) + "\n")
    return new_rows


def load_quantities(quantities_path: Path | None = None) -> list[dict]:
    return _read_jsonl(quantities_path or QUANTITIES_FILE)


def quantity_status(quantity_id: str, rows: list[dict], since_round: int = 0) -> str | None:
    """Status of a quantity's first estimate in the arc (None if never estimated)."""
    for r in sorted((r for r in rows if r.get("quantity_id") == quantity_id
                     and int(r.get("round", 0)) >= since_round
                     and r.get("status") != "not_computable"), key=lambda r: int(r["round"])):
        return r.get("status")
    return None


