def _fmt(v, nd: int = 2) -> str:
    if v is None:
        return "-"
    if isinstance(v, float):
        return f"{v:+.{nd}f}" if v != 0 else "0"
    return str(v)


def _relation(claim: dict | None, res: dict) -> str:
    if not claim:
        return ""
    lo, hi, thr = res.get("ci_low"), res.get("ci_high"), claim.get("threshold")
    if lo is None or hi is None or thr is None:
        return ""
    if isinstance(thr, list):
        a, b = sorted(float(x) for x in thr)
        if hi < a or lo > b:
            return "interval excludes the threshold range"
        return "interval overlaps the threshold range"
    thr = float(thr)
    parts = ["excludes threshold" if (hi < thr or lo > thr) else "includes threshold"]
    parts.append("excludes zero" if (hi < 0 or lo > 0) else "includes zero")
    return ", ".join(parts)


def compare_card(card: dict, results: dict) -> str:
    """Orchestrator-generated 'Card vs Observed' table appended to the
    Analyst post. Numbers come only from the results files."""
    lines = ["## Card vs Observed", "",
             "Generated by the orchestrator from the committed card and workspace results files.", "",
             "| Spec | Role | Claim | Committed threshold | Observed [interval] | N | Relation |",
             "|---|---|---|---|---|---|---|"]
    seen = set()
    for s in card.get("spec_plan") or []:
        sid = s.get("spec_id")
        seen.add(sid)
        cid = spec_claim_id(card, s)
        claim = claim_by_id(card, cid)
        thr = (claim or {}).get("threshold")
        res = results.get(sid)
        if res is None:
            obs, n, rel = "missing", "-", "no results file"
        elif str(res.get("status", "")).lower() == "not_computable":
            obs, n, rel = f"NOT COMPUTABLE ({res.get('missing_variable', 'reason not given')})", "-", ""
        else:
            obs = f"{_fmt(res.get('estimate'))} [{_fmt(res.get('ci_low'))}, {_fmt(res.get('ci_high'))}]"
            n, rel = _fmt(res.get("n")), _relation(claim, res)
        lines.append(f"| {sid} | {s.get('role')} | {cid} | {_fmt(thr)} | {obs} | {n} | {rel} |")
    for sid in sorted(set(results) - seen):
        res = results[sid]
        obs = f"{_fmt(res.get('estimate'))} [{_fmt(res.get('ci_low'))}, {_fmt(res.get('ci_high'))}]"
        tag = "exploratory" if sid.startswith("x_") else "NOT ON CARD"
        lines.append(f"| {sid} | {tag} | {res.get('claim_id', '-')} | - | {obs} | {_fmt(res.get('n'))} | |")
    return "\n".join(lines) + "\n"


def analyst_view(card: dict) -> dict:
    """The computation fields only, for a blinded opening-round Analyst
    (forum_config.blind_opening_analyst, off until D-13). Direction,
    thresholds, supporting and falsifying results, the decision rule and
    what each spec would mean are withheld."""
    view = {k: card.get(k) for k in ANALYST_VIEW_CARD_KEYS if k in card}
    view["spec_plan"] = [{k: s.get(k) for k in ANALYST_VIEW_SPEC_KEYS if k in s}
                         for s in card.get("spec_plan") or []]
    view["card_sha"] = card_sha(card)
    return view


def ledger_for_prompt(since_round: int, quantities_path: Path | None = None) -> str:
    """The active arc's quantities ledger as a compact table for prompts and
    the drafter. Numbers and statuses only."""
    rows = [r for r in load_quantities(quantities_path) if int(r.get("round", 0)) >= since_round]
    if not rows:
        return ""
    lines = ["\n## Arc Quantities Ledger (from knowledge/quantities.jsonl)\n",
             "| Round | Quantity | Spec | Estimate | Interval | N | Status |",
             "|---|---|---|---|---|---|---|"]
    for r in rows:
        ci = r.get("ci") or [None, None]
        lines.append(f"| R{r['round']} | {r.get('quantity_id')} | {r.get('spec_id')} | "
                     f"{_fmt(r.get('estimate'))} | [{_fmt(ci[0])}, {_fmt(ci[1])}] | "
                     f"{_fmt(r.get('n'))} | {r.get('status')} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description="Prediction cards and quantities ledger (Stage 2)")
    ap.add_argument("--write-schema", action="store_true", help="Regenerate knowledge/schemas/card.json")
    sub = ap.add_subparsers(dest="cmd")
    v = sub.add_parser("validate", help="Validate the card block of a post")
    v.add_argument("post")
    lg = sub.add_parser("ledger", help="Print the quantities ledger")
    lg.add_argument("--since", type=int, default=0)
    args = ap.parse_args()
    if args.write_schema:
        print(f"wrote {write_card_schema()}")
        return
    if args.cmd == "validate":
        card = extract_card(Path(args.post).read_text(encoding="utf-8"))
        errs = validate(card, prior_cards=load_cards())
        print("valid" if not errs else "\n".join(errs))
        sys.exit(0 if not errs else 1)
    if args.cmd == "ledger":
        print(ledger_for_prompt(args.since) or "(empty ledger)")
        return
    ap.print_help()


if __name__ == "__main__":
    main()
