#!/usr/bin/env python3
"""Prediction cards and the arc quantities ledger (M09, M19; Stage 2).

The Scout ends its 'Prediction to Test' section with a fenced ```card block of
JSON. The orchestrator extracts it, validates it, and commits it to
knowledge/prediction_cards/R<NN>.json before the Analyst starts, so the
prediction, its thresholds and its specification plan exist on disk before
anyone estimates anything. The Analyst runs exactly the committed specs, each
writing workspace/rNN/results/<spec_id>.json. ingest_results then turns those
files into knowledge/quantities.jsonl rows whose status says whether a number
was pre-committed (confirmatory), found in the data (exploratory), or tested
against a threshold set after the number was seen (post_hoc).

Everything here is behind forum_config.stage2.prediction_cards (off by
default). The module never calls Claude.

Card shape (see knowledge/schemas/card.json, generated by build_card_schema):

    {"claim_id", "kind": "prediction" | "reproduction", "quantity_id", "quantity",
     "population", "period", "comparison", "direction", "supporting_result",
     "decisive_metric", "falsifying_result", "threshold", "units",
     "decision_rule_quoted", "equivalence_bound", "claim_scope", "supersedes",
     "gap": {"gap_type": "a" | "b" | "c", "evidence": {...}},
     "claims": [ {secondary claim with the same claim keys} ],
     "spec_plan": [ {"spec_id", "role", "claim_id", "outcome_def", "sample_def",
                     "model", "expected_n", "what_result_would_mean"} ]}

Usage:
    python3 prediction_card.py --write-schema        # regenerate card.json
    python3 prediction_card.py validate <post.md>    # print validation errors
    python3 prediction_card.py ledger [--since R]    # print the quantities ledger
"""

