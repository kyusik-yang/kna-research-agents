def extract_card(post_text: str) -> dict | None:
    """The LAST ```card fenced block of the post, parsed as JSON. None if the
    post has no card block. A block that is not valid JSON yields
    {"_parse_error": "..."} so validate() can report it."""
    blocks = CARD_BLOCK_RE.findall(post_text or "")
    if not blocks:
        return None
    try:
        card = json.loads(blocks[-1])
    except json.JSONDecodeError as e:
        return {"_parse_error": f"card block is not valid JSON: {e}"}
    if not isinstance(card, dict):
        return {"_parse_error": "card block must be a JSON object"}
    return card


def all_claims(card: dict) -> list[dict]:
    """The card's headline claim followed by any secondary claims."""
    head = {k: card.get(k) for k in _claim_properties() if k in card}
    out = [head] if card.get("claim_id") else []
    out += [c for c in card.get("claims") or [] if isinstance(c, dict)]
    return out


def claim_by_id(card: dict, claim_id: str | None) -> dict | None:
    for c in all_claims(card):
        if c.get("claim_id") == claim_id:
            return c
    return None


def spec_claim_id(card: dict, spec: dict) -> str | None:
    return spec.get("claim_id") or card.get("claim_id")


def is_positive_headline(card: dict) -> bool:
    return card.get("kind", "prediction") == "prediction" and card.get("direction") in EFFECT_DIRECTIONS


def gap_record(card: dict) -> dict:
    """{"gap_type", "c_constructed"} for the card index (M19). A type (c) gap
    is constructed when either side's prediction is the Scout's inference."""
    gap = card.get("gap") or {}
    gtype = gap.get("gap_type")
    ev = gap.get("evidence") or {}
    constructed = False
    if gtype == "c":
        sides = [ev.get("lit_a") or {}, ev.get("lit_b") or {}]
        constructed = any(s.get("quantity_match") == "inferred" or not s.get("quoted_prediction")
                          for s in sides)
    return {"gap_type": gtype, "c_constructed": constructed}


def _norm_ws(s: str) -> str:
    return re.sub(r"\s+", " ", s or "").strip()


def _validate_claim(c: dict, where: str, kind: str, gate: dict | None) -> list[str]:
    errs = []
    if kind != "prediction":
        return errs
    for k in CLAIM_KEYS:
        v = c.get(k)
        if v is None or (isinstance(v, str) and not v.strip()):
            errs.append(f"{where}: missing '{k}'")
    thr = c.get("threshold")
    if thr is not None and not (_is_num(thr) or (isinstance(thr, list) and len(thr) == 2
                                                 and all(_is_num(x) for x in thr))):
        errs.append(f"{where}: threshold must be a number or [low, high]")
    if c.get("direction") is not None and c.get("direction") not in DIRECTIONS:
        errs.append(f"{where}: direction must be one of {list(DIRECTIONS)}")
    if c.get("equivalence_bound") is None and not (gate or {}).get("sesoi"):
        errs.append(f"{where}: missing 'equivalence_bound' (required whenever a null could be "
                    "reported, and the gate states no sesoi to default to)")
    rule = (gate or {}).get("decision_rule")
    if rule:
        q = c.get("decision_rule_quoted")
        if not q:
            errs.append(f"{where}: missing 'decision_rule_quoted' (the gate states a decision_rule)")
        elif _norm_ws(q) not in _norm_ws(rule):
            errs.append(f"{where}: decision_rule_quoted is not a verbatim part of the gate's decision_rule")
    return errs


def _is_num(x) -> bool:
    return isinstance(x, (int, float)) and not isinstance(x, bool)


def _validate_gap(card: dict) -> list[str]:
    gap = card.get("gap")
    if card.get("kind", "prediction") != "prediction":
        return []
    if not isinstance(gap, dict):
        return ["gap: missing (gap_type and evidence are required on prediction cards)"]
    gtype, ev = gap.get("gap_type"), gap.get("evidence") or {}
    if gtype not in GAP_TYPES:
        return [f"gap: gap_type must be one of {list(GAP_TYPES)}"]
    errs = []
    if gtype == "c":
        for side in ("lit_a", "lit_b"):
            s = ev.get(side)
            if not isinstance(s, dict):
                errs.append(f"gap.evidence.{side}: missing (doi, quoted_prediction, location, quantity_match)")
                continue
            if not DOI_RE.match(str(s.get("doi") or "")):
                errs.append(f"gap.evidence.{side}: doi missing or malformed")
            if s.get("quantity_match") not in QUANTITY_MATCH:
                errs.append(f"gap.evidence.{side}: quantity_match must be one of {list(QUANTITY_MATCH)}")
            if s.get("quoted_prediction") and not _location_kind(s.get("location")):
                errs.append(f"gap.evidence.{side}: location must be abstract, page N or section N")
        if gap_record(card)["c_constructed"] and not ev.get("own_derivation"):
            errs.append("gap: c_constructed. At least one side's prediction is inferred or unquoted. "
                        "Reclassify the gap as (a) or (b), or keep (c) with evidence.own_derivation "
                        "true and present the rival prediction as your own derivation.")
    elif gtype == "a":
        if not DOI_RE.match(str(ev.get("theory_source") or "")):
            errs.append("gap.evidence.theory_source: DOI of the theory source required for (a)")
        for k in ("quoted_prediction", "magnitude"):
            if not ev.get(k):
                errs.append(f"gap.evidence.{k}: required for (a)")
    elif gtype == "b":
        for k in ("measure", "why_unavailable", "available_since"):
            if not ev.get(k):
                errs.append(f"gap.evidence.{k}: required for (b)")
    return errs


def _location_kind(loc) -> str | None:
    s = str(loc or "").strip().lower()
    for kind in QUOTE_LOCATIONS:
        if s.startswith(kind):
            return kind
    return None


def validate(card: dict | None, gate: dict | None = None,
             prior_cards: dict | None = None) -> list[str]:
    """List of problems with a card, empty when it may be committed.

    gate: the arc's topic_gate fields (decision_rule, sesoi) when known.
    prior_cards: {round: card} committed earlier in the season, for the rule
    that a changed threshold on an existing claim_id needs supersedes."""
    if card is None:
        return ["no ```card block found"]
    if "_parse_error" in card:
        return [card["_parse_error"]]
    errs = schema_errors(card, build_card_schema())
    kind = card.get("kind", "prediction")
    specs = [s for s in card.get("spec_plan") or [] if isinstance(s, dict)]
    claims = all_claims(card)
    claim_ids = [c.get("claim_id") for c in claims]
    if len(set(claim_ids)) != len(claim_ids):
        errs.append("claims: duplicate claim_id")
    for i, c in enumerate(claims):
        errs += _validate_claim(c, "card" if i == 0 else f"claims[{i - 1}]", kind, gate)
    # Specification plan
    if len(specs) > MAX_SPECS:
        errs.append(f"spec_plan: {len(specs)} specs, at most {MAX_SPECS} (one primary and five others)")
    roles = [s.get("role") for s in specs]
    if kind == "prediction" and roles.count("primary") != 1:
        errs.append(f"spec_plan: exactly one primary spec required, found {roles.count('primary')}")
    if kind == "reproduction" and any(r in KILL_ROLES for r in roles):
        errs.append("spec_plan: a reproduction-only plan may hold only reproduction, calibration or sanity specs")
    ids = [s.get("spec_id") for s in specs]
    if len(set(ids)) != len(ids):
        errs.append("spec_plan: duplicate spec_id")
    for s in specs:
        sid = str(s.get("spec_id") or "?")
        if not SPEC_ID_RE.match(sid):
            errs.append(f"spec {sid}: spec_id must be an identifier")
        if sid.startswith("x_"):
            errs.append(f"spec {sid}: x_ ids are reserved for exploratory results, not planned specs")
        if not str(s.get("what_result_would_mean") or "").strip():
            errs.append(f"spec {sid}: what_result_would_mean is required for every role")
        cid = spec_claim_id(card, s)
        if cid not in claim_ids:
            errs.append(f"spec {sid}: claim_id {cid!r} is not a claim on this card")
        if s.get("role") == "calibration":
            src = s.get("source") or {}
            if not (DOI_RE.match(str(src.get("doi") or "")) and (src.get("table") or src.get("page"))):
                errs.append(f"spec {sid}: a calibration spec needs a cited DOI and the table or page "
                            "value the Scout read, otherwise it is NOT APPLICABLE")
        if s.get("role") == "sanity" and s.get("sanity_kind") is not None \
                and s.get("sanity_kind") not in SANITY_KINDS:
            errs.append(f"spec {sid}: sanity_kind must be one of {list(SANITY_KINDS)}")
    if is_positive_headline(card):
        kinds = {s.get("sanity_kind") for s in specs if s.get("role") == "sanity"}
        for need in SANITY_KINDS:
            if need not in kinds:
                errs.append(f"spec_plan: an effect claim needs a '{need}' sanity spec "
                            "(permuted outcome within assembly term, 200 draws, and 90 percent "
                            "legislator subsamples, 50 draws)")
    errs += _validate_gap(card)
    if prior_cards:
        errs += _supersession_errors(card, prior_cards)
    return errs


validate_card = validate


def _supersession_errors(card: dict, prior_cards: dict) -> list[str]:
    errs = []
    earlier = {}
    for r in sorted(prior_cards):
        for c in all_claims(prior_cards[r]):
            earlier[c.get("claim_id")] = c
    sup = {c.get("supersedes") for c in all_claims(card) if c.get("supersedes")}
    for c in all_claims(card):
        cid = c.get("claim_id")
        old = earlier.get(cid)
        if old is None:
            continue
        # A value that is not restated (None, as on a reproduction card) is not a change.
        changed = any(c.get(k) is not None and old.get(k) != c.get(k)
                      for k in ("threshold", "equivalence_bound"))
        if changed and cid not in sup:
            errs.append(f"claim {cid}: threshold changed from {old.get('threshold')!r} to "
                        f"{c.get('threshold')!r} without 'supersedes'")
    return errs


def continuation_message(errors: list[str]) -> str:
    """Resume message for one Scout retry after an invalid card (shares the
    M11 continuation cap)."""
    lines = "\n".join(f"- {e}" for e in errors[:20])
    return ("Your ```card block did not validate, so the round cannot start the Analyst. "
            "Fix these problems in the same post, keep the rest of the post unchanged, and "
            f"end 'Prediction to Test' with the corrected card block.\n{lines}")


